// Markdown tables for a label: median and max per cell (H5). Reads every run JSON under the label
// directory, so a label built by several invocations gets one table.
// CLI: node scripts/field-vitals/lib/report.mjs <labelDir>
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

export const median = (xs) => {
  const v = xs.filter((x) => x != null && !Number.isNaN(x)).sort((a, b) => a - b);
  if (!v.length) return null;
  const m = Math.floor(v.length / 2);
  return v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2;
};
export const max = (xs) => {
  const v = xs.filter((x) => x != null && !Number.isNaN(x));
  return v.length ? Math.max(...v) : null;
};
const f4 = (x) => (x == null ? "n/a" : x.toFixed(4));
const ms = (x) => (x == null ? "n/a" : String(Math.round(x)));
const kb = (x) => (x == null ? "n/a" : (x / 1024).toFixed(1));

export function listRunFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      if (statSync(p).isDirectory()) walk(p);
      else if (/-run\d+\.json$/.test(n) && !n.startsWith("keep-")) out.push(p);
    }
  };
  walk(dir);
  return out.sort();
}

const adOrder = (a) => (a === "noad" ? 999 : /^d(\d+)$/.test(a) ? +a.slice(1) : 500);
const mode = (xs) => {
  const c = new Map();
  for (const x0 of xs) { const x = clean(x0); if (x) c.set(x, (c.get(x) || 0) + 1); }
  let best = null, n = 0;
  for (const [k, v] of c) if (v > n) { best = k; n = v; }
  return best ? (n > 1 ? `${best} (${n}x)` : best) : "none";
};
const clean = (x) => (typeof x === "string" ? x.replace(/\S*base64,\S*/g, "(data URI)").replace(/\|/g, "/") : x);
const uniq = (xs) => [...new Set(xs.filter((x) => x != null && x !== ""))];

export function groupRuns(summaries) {
  const g = new Map();
  for (const s of summaries) {
    const k = `${s.cell}\u0000${s.ad}`;
    if (!g.has(k)) g.set(k, []);
    g.get(k).push(s);
  }
  return [...g.values()].sort((a, b) => (a[0].cell === b[0].cell ? adOrder(a[0].ad) - adOrder(b[0].ad) : a[0].cell < b[0].cell ? -1 : 1));
}

export function renderTables(label, summaries) {
  const groups = groupRuns(summaries);
  const L = [];
  L.push(`# Field vitals: ${label}`, "");
  L.push(`Generated by \`scripts/field-vitals\` on ${new Date().toISOString()}. ${summaries.length} runs. Raw JSON per run is gitignored; its sha256 is in \`manifest.json\`.`, "");
  L.push("## Stability", "");
  L.push("Windowed CLS is the largest session window (1 s gap, 5 s cap) without `hadRecentInput` entries, the number Chrome reports. \"+input\" counts those entries too. Total is the sum of every shift. Top source is the most common largest-entry source in each run's worst window.", "");
  L.push("| Cell | Ad | N | CLS win med | CLS win max | win +input max | total med | total max | runs >= 0.1 | runs >= 0.25 | top source | worst window start (ms, med) |");
  L.push("|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const rs of groups) {
    const s = rs[0];
    L.push(`| ${s.cell} | ${s.ad} | ${rs.length} | ${f4(median(rs.map((r) => r.clsWin)))} | ${f4(max(rs.map((r) => r.clsWin)))} | ${f4(max(rs.map((r) => r.clsWinIn)))} | ${f4(median(rs.map((r) => r.clsTot)))} | ${f4(max(rs.map((r) => r.clsTot)))} | ${rs.filter((r) => r.clsWin >= 0.1).length} | ${rs.filter((r) => r.clsWin >= 0.25).length} | ${mode(rs.map((r) => r.topSource))} | ${ms(median(rs.map((r) => r.worstStart)))} |`);
  }
  L.push("", "## Loading", "");
  L.push("Times in ms from navigation start, median over N (LCP also max). Hero image = first request under `/images/season1/`; bytes = encodedBodySize summed over hero images. Fonts CSS end = the Google Fonts stylesheet response end. First long task = first task of 50 ms or more.");
  L.push("");
  L.push("| Cell | Ad | N | first paint | FCP | LCP med | LCP max | LCP element | hero img start | hero img end | hero KB | fonts CSS end | first long task start / dur | long tasks | INP max |");
  L.push("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const rs of groups) {
    const s = rs[0];
    L.push(`| ${s.cell} | ${s.ad} | ${rs.length} | ${ms(median(rs.map((r) => r.firstPaint)))} | ${ms(median(rs.map((r) => r.fcp)))} | ${ms(median(rs.map((r) => r.lcp)))} | ${ms(max(rs.map((r) => r.lcp)))} | ${mode(rs.map((r) => r.lcpEl))} | ${ms(median(rs.map((r) => r.heroImgStart)))} | ${ms(median(rs.map((r) => r.heroImgEnd)))} | ${kb(median(rs.map((r) => r.heroImgBytes)))} | ${ms(median(rs.map((r) => r.fontsCssEnd)))} | ${ms(median(rs.map((r) => r.lt1Start)))} / ${ms(median(rs.map((r) => r.lt1Dur)))} | ${ms(median(rs.map((r) => r.ltCount)))} | ${ms(max(rs.map((r) => r.inp)))} |`);
  }
  L.push("", "## Checks", "");
  L.push("s1Ready and s1-pre are the OR2 sentinels (absent before Atlas's slice). S2 = hero images whose box changes when the image's intrinsic size changes (offender count, max over N). U-6 = families painted on visible text but not requested by the page's font links. Form usable = an invalid email shows the client error text with no request (local targets only). POSTs = aborted `/api/*` writes. Analytics = blocked attempts; leaks = analytics responses that did not come from the harness's block.");
  L.push("");
  L.push("| Cell | Ad | N | marker | s1Ready | s1-pre | hero state | S2 offenders | U-6 offenders | form usable | page errors | POSTs | analytics attempts | leaks |");
  L.push("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|");
  for (const rs of groups) {
    const s = rs[0];
    const fu = rs.map((r) => r.formUsable).filter((x) => x != null);
    L.push(`| ${s.cell} | ${s.ad} | ${rs.length} | ${uniq(rs.map((r) => r.marker || "absent")).join(", ")} | ${uniq(rs.map((r) => r.s1Ready || "absent")).join(", ")} | ${uniq(rs.map((r) => r.s1Pre || "absent")).join(", ")} | ${uniq(rs.map((r) => r.heroState)).join("; ")} | ${max(rs.map((r) => r.s2Off))} | ${uniq(rs.flatMap((r) => r.u6Off || [])).join(", ") || "none"} | ${fu.length ? `${fu.filter(Boolean).length}/${fu.length}` : "not run"} | ${max(rs.map((r) => r.pageErrors))} | ${rs.reduce((a, r) => a + (r.posts || 0), 0)} | ${rs.reduce((a, r) => a + (r.analyticsAttempts || 0), 0)} | ${rs.reduce((a, r) => a + (r.leaks || 0), 0)} |`);
  }
  L.push("");
  return L.join("\n");
}

export function writeReport(labelDir, label) {
  const files = listRunFiles(labelDir);
  const summaries = files.map((f) => ({ ...JSON.parse(readFileSync(f, "utf8")).summary, file: relative(labelDir, f) }));
  const md = renderTables(label, summaries);
  writeFileSync(join(labelDir, "table.md"), md);
  return { md, summaries };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dir = process.argv[2];
  if (!dir) { console.error("usage: node report.mjs <labelDir>"); process.exit(1); }
  const { md } = writeReport(dir, dir.split("/").filter(Boolean).pop());
  console.log(md);
}
